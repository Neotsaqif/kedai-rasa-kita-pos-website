-- Helper function to check admin role
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin' AND is_active = true
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- PROFILES POLICIES
CREATE POLICY "Users can read own profile" ON public.profiles
  FOR SELECT USING (auth.uid() = id OR public.is_admin());
CREATE POLICY "Admins can insert/update profiles" ON public.profiles
  FOR ALL USING (public.is_admin());

-- CATEGORIES POLICIES
CREATE POLICY "Authenticated users can read categories" ON public.categories
  FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Admins can manage categories" ON public.categories
  FOR ALL USING (public.is_admin());

-- PRODUCTS POLICIES
CREATE POLICY "Authenticated users can read products" ON public.products
  FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Admins can manage products" ON public.products
  FOR ALL USING (public.is_admin());

-- SALES & SALE ITEMS POLICIES
CREATE POLICY "Authenticated users can create and read sales" ON public.sales
  FOR ALL USING (auth.role() = 'authenticated');
CREATE POLICY "Authenticated users can create and read sale items" ON public.sale_items
  FOR ALL USING (auth.role() = 'authenticated');

-- STOCK LOGS POLICIES
CREATE POLICY "Authenticated users can read stock logs" ON public.stock_logs
  FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Admins can manage stock logs" ON public.stock_logs
  FOR ALL USING (public.is_admin());

-- Atomic checkout function (RPC)
CREATE OR REPLACE FUNCTION process_checkout(
  p_receipt_number TEXT,
  p_cashier_id UUID,
  p_total_amount DECIMAL,
  p_payment_method TEXT,
  p_items JSONB
) RETURNS BIGINT AS $$
DECLARE
  v_sale_id BIGINT;
  item RECORD;
BEGIN
  -- 1. Insert Sales Record
  INSERT INTO public.sales (receipt_number, cashier_id, total_amount, payment_method)
  VALUES (p_receipt_number, p_cashier_id, p_total_amount, p_payment_method)
  RETURNING id INTO v_sale_id;

  -- 2. Process Items & Update Stock
  FOR item IN SELECT * FROM jsonb_to_recordset(p_items) AS x(product_id BIGINT, product_name TEXT, qty INT, price DECIMAL)
  LOOP
    -- Insert Sale Item
    INSERT INTO public.sale_items (sale_id, product_id, product_name, qty, price_at_sale)
    VALUES (v_sale_id, item.product_id, item.product_name, item.qty, item.price);

    -- Decrement Product Stock
    UPDATE public.products
    SET stock_qty = stock_qty - item.qty
    WHERE id = item.product_id AND stock_qty >= item.qty;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Insufficient stock for product ID %', item.product_id;
    END IF;

    -- Insert Stock Log
    INSERT INTO public.stock_logs (product_id, change_qty, reason)
    VALUES (item.product_id, -item.qty, 'sale');
  END LOOP;

  RETURN v_sale_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

